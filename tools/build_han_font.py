"""Pack the Simplified Chinese UI glyphs from Noto Sans SC for the RGB565 renderer."""

import argparse
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont


SIZE = 14
ROOT = Path(__file__).resolve().parents[1]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("font", type=Path, help="path to NotoSansSC-VF.ttf")
    args = parser.parse_args()
    font = ImageFont.truetype(args.font, SIZE - 1)
    if font.getname()[0] != "Noto Sans SC":
        parser.error("use the Noto Sans SC variable font")
    font.set_variation_by_axes([500])

    sources = [ROOT / "src" / name for name in ("art.c", "ui_labels.inc")]
    characters = sorted({character for source in sources for character in source.read_text(encoding="utf-8")
                         if "\u3400" <= character <= "\u9fff"})
    output = ["/* Generated by tools/build_han_font.py. See OFL-NotoSansSC.txt. */"]
    for character in characters:
        image = Image.new("L", (SIZE, SIZE), 0)
        left, top, right, bottom = font.getbbox(character)
        x = (SIZE - (right - left)) // 2 - left
        y = (SIZE - (bottom - top)) // 2 - top
        ImageDraw.Draw(image).text((x, y), character, font=font, fill=255)
        rows = [sum(1 << col for col in range(SIZE) if image.getpixel((col, row)) >= 98)
                for row in range(SIZE)]
        if not any(rows):
            raise ValueError(f"Empty glyph for {character}")
        output.append(f"\t{{0x{ord(character):04x}, {{{', '.join(f'0x{row:04x}' for row in rows)}}}}},")

    (ROOT / "src" / "ui_glyphs.inc").write_text("\n".join(output) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
